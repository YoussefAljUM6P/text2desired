"""Tables of the paper experiments from the csv files (any subset may be missing or partial).

  ~/anaconda3/envs/pca_servo/bin/python scripts/summarize_experiments.py      (from my_code/)
Writes out/experiments_summary.md.
"""
import csv
from collections import defaultdict
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parents[1] / "out"


def read(p):
    return list(csv.DictReader(open(p))) if p.exists() else []


def servo_table(files):
    lines = ["| desired images | current views | perturbation (t / d*, rot) | runs | success (%) | median final t / d* | median final rot (deg) |",
             "|---|---|---|---|---|---|---|"]
    for label, path in files:
        R = read(path)
        by = defaultdict(list)
        for r in R:
            by[(r["alpha"], r["beta"])].append(r)
        for (a, b), rs in sorted(by.items()):
            src = rs[0]["source"]
            lines.append(f"| {label} | {'same model' if src == 'same' else 'other model (LangSplat-V2 RGB 3DGS)'} | "
                         f"{float(a):.1f} / {float(b):.0f} deg | {len(rs)} | {100 * np.mean([int(r['success']) for r in rs]):.1f} | "
                         f"{np.median([float(r['t_err_rel']) for r in rs]):.4f} | {np.median([float(r['r_err']) for r in rs]):.3f} |")
    return lines


def sensitivity_table(files):
    lines = ["| dataset | variant | queries | same view (angle < 5 deg, %) | median angle (deg) | median d / d* | "
             "whole object in image (%) | median support |", "|---|---|---|---|---|---|---|---|"]
    for label, path in files:
        R = read(path)
        by = defaultdict(list)
        for r in R:
            by[r["variant"]].append(r)
        for v, rs in by.items():
            ang = [float(r["angle_to_frozen_deg"]) for r in rs]
            lines.append(f"| {label} | {v} | {len(rs)} | {100 * np.mean(np.array(ang) < 5):.0f} | {np.median(ang):.1f} | "
                         f"{np.median([float(r['d_ratio']) for r in rs]):.2f} | "
                         f"{100 * np.mean([float(r['in_image']) >= 0.98 for r in rs]):.0f} | "
                         f"{np.median([float(r['support']) for r in rs]):.2f} |")
    return lines


def main():
    md = ["# Project A experiments (generated by scripts/summarize_experiments.py)", "",
          "## Photometric servo toward the desired image", "",
          "Success: final position error < 2 % of d* and rotation error < 1 deg (servo at 320 px width, LM, 600 it max).", ""]
    md += servo_table([("ours, Mip-NeRF 360", OUT / "servo_eval/mipnerf360_same.csv"),
                       ("ours, LERF-OVS", OUT / "servo_eval/lerf_ovs_same.csv"),
                       ("ours, LERF-OVS", OUT / "servo_eval/lerf_ovs_cross.csv"),
                       ("B1 training photo, LERF-OVS", OUT / "servo_eval/baseline_refview_same.csv"),
                       ("B2 CLIP render-and-score, LERF-OVS", OUT / "servo_eval/baseline_clip_same.csv"),
                       ("B3 CapFrame, LERF-OVS", OUT / "servo_eval/baseline_capframe_same.csv")])
    md += ["", "## Desired-image benchmark (LERF-OVS, GT 3D objects)", ""]
    s = OUT / "benchmark/summary.md"
    md += s.read_text().splitlines() if s.exists() else ["(not run yet)"]
    md += ["", "## Sensitivity of the viewpoint selection (vs the frozen choice)", ""]
    md += sensitivity_table([("Mip-NeRF 360", OUT / "sensitivity/mipnerf360.csv"),
                             ("LERF-OVS", OUT / "sensitivity/lerf_ovs.csv")])
    (OUT / "experiments_summary.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
